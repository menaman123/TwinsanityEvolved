// Binds `memory` to the engine's 32 MB array: 512 pages of 64 KiB, fixed (max == initial), software bounds checks
// (WASM_RT_MEMCHECK_BOUNDS_CHECK: the bytes are a std::vector the engine owns, not an mmap with guard pages).
void BindMainMemory(w2c_env& env, MainMemory& ram);
#else
// The native lane: env.memory = the guest block (te_native.h), te_host.h's GuestMemory() = the block
void BindGuestBlock(w2c_env& env);
#endif

struct RetailImage {
    uint32_t start = 0x2D9D90;   // .vutext start (PAL SLES-52568)
    uint32_t end = 0x3DB200;     // .bss end
    uint32_t bss_start = 0x30A480;   // .sbss start: zero from here (the ELF carries no bytes for it)
    uint32_t code_start = 0x00100000;
    uint32_t code_end = 0x002D9D90;
};

// Loads the retail data image from the PAL ELF's bytes into the module memory at its retail addresses. Only the
// [start, bss_start) bytes are copied (from the PT_LOAD segment that covers them); .sbss/.bss stay zero. Returns false
// with *error when the ELF is not the PAL SLES_525.68 layout (entry 0x100008, a PT_LOAD covering the image).
bool LoadRetailImage(w2c_env& env, const std::vector<uint8_t>& elf, const RetailImage& image, std::string* error);

// Reads the ELF `path_in_iso` (e.g. "SLES_525.68") out of a disc image with the engine's IsoFs.
bool ReadElfFromIso(const std::string& iso_path, const std::string& path_in_iso, std::vector<uint8_t>& out, std::string* error);
// The same out of a volume already open -- the services' disc (te::Disc::Iso()), which is the mods' overlay when one is on:
// a mod's own executable is the one the data image is loaded from.
bool ReadElfFromDisc(const IsoFs& disc, const std::string& path_in_iso, std::vector<uint8_t>& out, std::string* error);

// `count` words of the ELF's loaded image from `vaddr` (the PT_LOAD segment's file bytes that hold them); false when no
// segment does. Diagnosis only (te_math_diag.h: the retail VU0 functions run on the engine's VU interpreter).
bool ReadRetailWords(const std::vector<uint8_t>& elf, uint32_t vaddr, uint32_t count, std::vector<uint32_t>& out);

struct PatchReport {
    uint32_t words_scanned = 0;
    uint32_t patched = 0;            // retail code address -> table index
    uint32_t unported_hits = 0;      // a retail function start with NO body in the module (left as the address)
    uint32_t stray_code_range = 0;   // in the code range but not a known function start (left alone)
    std::vector<std::pair<uint32_t, uint32_t>> unported;   // (word address, retail function address)
};

// Rewrites every 4-byte word of .data/.rodata/.sdata (0x2E6F00..0x30A460) holding a retail CODE address into the wasm
// table index of the function of that name, using the module's exported te_retail_functions table
// (tools/gen_retail_table.py). `known_function_starts` (every type:func in symbol_addrs.txt) tells unported bodies
// from stray integers.
PatchReport PatchRetailCodePointers(w2c_env& env, const std::vector<uint32_t>& known_function_starts);

struct VtableThunkReport {
    uint32_t slots_checked = 0;      // vtable slot rows (tools/vtable_slots.tsv) whose word holds a patched body
    uint32_t matched = 0;            // the body already has the slot's declared type
    uint32_t thunked = 0;            // repointed to a pool thunk of the declared type (forwards to the body)
    uint32_t pure = 0;               // the pure-virtual body: the shared per-signature thunk
    uint32_t beyond_vtable = 0;      // the slot word lies past this vtable's end (another vtable starts first)
    uint32_t unported = 0;           // the slot holds an unported retail address (left as is; traps if called)
    uint32_t pool_exhausted = 0;     // no thunk instance left for that signature (left as is; raise TE_VT_POOL)
    uint32_t already = 0;            // a second row for the same word (conflicts): skipped
    std::vector<std::string> pool_exhausted_signatures;
    std::vector<std::pair<uint32_t, uint32_t>> thunked_words;   // (word address, body table index)
};

// after the code pointers are patched, every vtable slot the decomp calls (the host table generated from
// tools/vtable_slots.tsv) is checked against the slot's declared module type; a body of another type is replaced by
// a thunk instance of the declared type whose target (te_vt_targets[k]) is set to the body's table index.
VtableThunkReport PatchVtableThunks(w2c_env& env, bool verbose);

// The call-site type adapters wasm2c's CALL_INDIRECT falls back to on a mismatch no slot thunk caught
struct AdaptReport {
    uint64_t calls = 0;   // adapted indirect calls so far
    uint32_t sites = 0;   // distinct (caller's type, callee index) pairs
};
AdaptReport AdaptedCalls();

