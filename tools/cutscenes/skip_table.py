#!/usr/bin/env python3
"""tools/cutscenes/skip_table.py -- the table of the scripted cutscenes the cross button may skip, made of the cutscene skip
judge's fixture (fixtures/judges/cutscene_skip_pal.json).

Each cutscene of the fixture names its site (the graph that runs its CutsceneStart, as tools/cutscenes/census.py finds them),
the graphs only it runs (`graphs`: the site's own and its child behaviours' -- the director's runner runs one of them as the
cutscene starts, the content it plays after) and its status: "pass" (its skip was verified to leave what watching it leaves:
skippable) or "refused" (it cannot be skipped, `why` says why in plain words: the cross button does nothing in it and it plays
as watched). A director may direct several cutscenes (one a chunk, a boss fight's start and its end): a passing one's
`unverified` graphs are those its verified legs never ran (the director's other cutscenes, its fight), refused as not checked.
The table is one row per graph; the host answers Platform::System::CutsceneSkippable from it
(platform/nativeee/host/cutscene_skip.cpp).

  tools/cutscenes/skip_table.py --fixture FIXTURE --out FILE.cpp     the table (the build makes it: platform/nativeee/CMakeLists.txt)
  tools/cutscenes/skip_table.py --fixture FIXTURE --list             the cutscenes that cannot be skipped and why
"""
import argparse
import json
import os
import sys

STATUSES = ("pass", "refused")
# a passing cutscene's director's graphs its verified legs never ran
UNVERIFIED = "not verified: another of its director's cutscenes or its fight (%s was checked)"


def load(path):
    """The fixture's cutscenes, checked: a site and graphs each, a status, a reason when refused, no graph in two cutscenes."""
    fixture = json.load(open(path, encoding="utf-8"))
    rows, owner = [], {}
    for item in fixture["cutscenes"]:
        name = item.get("name", "?")
        site = item.get("site")
        graphs = item.get("graphs", [])
        status = item.get("status")
        why = item.get("why", "")
        if not isinstance(site, int) or not 0 <= site <= 0xFFFF:
            raise SystemExit("skip_table: %s: no site" % name)
        if site not in graphs:
            raise SystemExit("skip_table: %s: its graphs do not name its site %d" % (name, site))
        if status not in STATUSES:
            raise SystemExit("skip_table: %s: status %r is none of %s" % (name, status, ", ".join(STATUSES)))
        if status == "refused" and not why:
            raise SystemExit("skip_table: %s: refused without a reason" % name)
        if not all(32 <= ord(c) < 127 for c in why):
            raise SystemExit("skip_table: %s: the reason is not plain ASCII" % name)
        unverified = item.get("unverified", [])
        if status != "pass" and unverified:
            raise SystemExit("skip_table: %s: unverified graphs of a refused cutscene (all of its graphs are refused)" % name)
        if not set(unverified) <= set(graphs) or site in unverified:
            raise SystemExit("skip_table: %s: its unverified graphs are not among its graphs, or name its site" % name)
        for g in graphs:
            if not isinstance(g, int) or not 0 <= g <= 0xFFFF:
                raise SystemExit("skip_table: %s: graph %r" % (name, g))
            if g in owner and owner[g] != name:
                raise SystemExit("skip_table: graph %d is in two cutscenes (%s, %s)" % (g, owner[g], name))
            owner[g] = name
        rows.append({"name": name, "label": item.get("label", name), "site": site, "graphs": sorted(set(graphs)),
                     "unverified": sorted(set(unverified)), "skippable": status == "pass", "why": why if status != "pass" else ""})
    return rows


def source(rows, fixture):
    out = ["// generated by tools/cutscenes/skip_table.py from %s -- do not edit" % fixture.replace("\\", "/"),
           '#include "te_cutscene_skip.h"', "", "namespace te::cutscene_skip {", "", "const Graph kGraphs[] = {"]
    count = 0
    for r in sorted(rows, key=lambda r: r["site"]):
        for g in r["graphs"]:
            skippable = r["skippable"] and g not in r["unverified"]
            why = r["why"] if g not in r["unverified"] else UNVERIFIED % r["label"]
            out.append("    {%d, %d, %d, %s},  // %s" % (g, r["site"], 1 if skippable else 0, json.dumps(why if not skippable else ""), r["name"]))
            count += 1
    out += ["};", "const unsigned kGraphCount = %du;" % count, "", "}  // namespace te::cutscene_skip", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fixture", required=True)
    ap.add_argument("--out")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    rows = load(a.fixture)
    if a.list:
        for r in rows:
            if not r["skippable"]:
                print("%-34s site %5d  %s" % (r["name"], r["site"], r["why"]))
            elif r["unverified"]:
                print("%-34s site %5d  skippable; not verified, so refused: its graphs %s" % (r["name"], r["site"],
                                                                                          " ".join(map(str, r["unverified"]))))
        print("skip_table: %d cutscenes, %d skippable (%d of them with other graphs not verified), %d cannot be skipped" % (
            len(rows), sum(r["skippable"] for r in rows), sum(1 for r in rows if r["skippable"] and r["unverified"]),
            sum(not r["skippable"] for r in rows)))
    if a.out:
        text = source(rows, os.path.relpath(a.fixture, os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))))
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
