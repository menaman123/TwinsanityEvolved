#!/usr/bin/env python3
"""gen_retail_image.py -- the retail data image as ONE zero-filled wasm data segment with every retail data symbol at
its retail offset (the bytes come from the disc's ELF at RUN time, only ADDRESSES live in the tree).

The decomp links the retail `.vutext .data .rodata .sdata .sbss .bss` (0x2D9D90..0x3DB200, PAL SLES-52568) from the
split executable and refers to 1,200+ retail variables by name (`RETAIL(D_xxxxxxxx)`, `RETAIL(GameNode_Methods)`, ...).
wasm-ld has no --defsym and no absolute data symbols, so this script emits an assembly file defining a single segment
`te_retail_image` of the image's size with a label (and `.size`) for every retail data symbol the game's objects
reference, at `address - 0x2D9D90`. Linked LAST as a .bss section (tools/link_wasm.py's two passes put the C++'s data below it), the segment lands exactly on the retail
addresses and every label IS its retail address. The runner fills the bytes from the ELF's program headers before entry.

Symbol sources: `symbol_addrs.txt` (every non-function symbol inside the range) and the `D_XXXXXXXX` names (address in
the name) the objects leave undefined (llvm-nm -u).

    gen_retail_image.py --game GAME_ROOT --nm LLVM_NM --out image.s [--json image.json] obj1.o obj2.o ...

--arm (the PlayStation Vita's native build, CMake TE_VITA_NATIVE): the same symbols as an ARM (GNU as) file instead --
`te_guest_block`, a 32 MB .bss array (4 KB aligned: a 64 KB alignment makes ld emit the third PT_LOAD vita-elf-create
refuses), the game's whole retail address space: every retail data symbol is defined at te_guest_block + its retail
address, `__heap_base` at the image's end (0x3DB200, the C library's break as in the wasm module), so the retail image the
runner loads from the disc lands at te_guest_block + 0x2D9D90 and the game's heap (platform/nativeee/wasm/memory.cpp) at
te_guest_block + 0x3F6480 .. + 0x2000000: the wasm module's offsets, bit for bit, in native memory.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rspfile  # noqa: E402

IMAGE_START = 0x2D9D90   # .vutext start (tools/make_ld.py DATA_SECTIONS)
IMAGE_END = 0x3DB200     # .bss end
# The retail layout, for the runner's loader (section, start, end)
SECTIONS = [(".vutext", 0x2D9D90, 0x2E6ED0), (".data", 0x2E6F00, 0x2EC3D2), (".rodata", 0x2EC400, 0x309868),
            (".sdata", 0x309880, 0x30A460), (".sbss", 0x30A480, 0x30ACD8), (".bss", 0x30AD00, 0x3DB200)]


def read_symbol_addrs(path):
    syms = {}
    for line in path.read_text().splitlines():
        m = re.match(r"(\w+)\s*=\s*0x([0-9A-Fa-f]+);\s*(?://\s*(.*))?", line)
        if not m:
            continue
        name, addr, rest = m.group(1), int(m.group(2), 16), (m.group(3) or "")
        size = None
        ms = re.search(r"size:0x([0-9A-Fa-f]+)", rest)
        if ms:
            size = int(ms.group(1), 16)
        syms[name] = {"addr": addr, "func": "type:func" in rest or "jtbl_label" in rest, "size": size, "rest": rest}
    return syms


def undefined_symbols(nm, objects, rsp):
    und = set()
    r = subprocess.run([nm, *rspfile.tool_args(["-u", *objects], rsp)], capture_output=True, text=True)
    for line in r.stdout.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[-2] == "U":
            und.add(parts[-1])
    return und


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--game", required=True)
    ap.add_argument("--nm", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--json", default=None)
    ap.add_argument("--arm", action="store_true", help="the native build's guest block (ARM GNU as) instead of the wasm segment")
    ap.add_argument("objects", nargs="*")
    a = ap.parse_args(rspfile.expand_argv(sys.argv[1:]))

    syms = read_symbol_addrs(Path(a.game) / "symbol_addrs.txt")
    und = undefined_symbols(a.nm, a.objects, a.out + ".nm.rsp") if a.objects else set()

    labels = {}  # addr -> [(name, size)]
    def add(name, addr, size):
        if not (IMAGE_START <= addr < IMAGE_END):
            return False
        labels.setdefault(addr, []).append((name, size))
        return True

    unresolved_outside = []
    for name, s in syms.items():
        if s["func"]:
            continue
        if not add(name, s["addr"], s["size"]):
            if name in und:
                unresolved_outside.append((name, hex(s["addr"])))
    for name in sorted(und):
        m = re.fullmatch(r"D_([0-9A-F]{8})", name)
        if m and name not in syms:
            if not add(name, int(m.group(1), 16), None):
                unresolved_outside.append((name, m.group(1)))

    addrs = sorted(labels)
    if a.arm:
        guest_size = 0x2000000
        lines = ["@ GENERATED by tools/gen_retail_image.py --arm -- DO NOT EDIT. The native build's guest block: the game's 32 MB",
                 "@ retail address space as a .bss array (zero; the retail image's bytes are loaded from the disc at run time),",
                 f"@ every retail data symbol the game references AT te_guest_block + its retail address ({len(addrs)} addresses,",
                 f"@ {sum(len(v) for v in labels.values())} symbols), the C library's break (__heap_base) at the image's end.",
                 '\t.section\t.bss.te_guest_block,"aw",%nobits', "\t.balign\t4096", "\t.globl\tte_guest_block",
                 "\t.type\tte_guest_block, %object", "te_guest_block:", f"\t.space\t0x{guest_size:X}",
                 f"\t.size\tte_guest_block, 0x{guest_size:X}",
                 "\t.globl\t__heap_base", "\t.type\t__heap_base, %object", f"\t.set\t__heap_base, te_guest_block + 0x{IMAGE_END:X}",
                 "\t.globl\tte_retail_image", "\t.type\tte_retail_image, %object",
                 f"\t.set\tte_retail_image, te_guest_block + 0x{IMAGE_START:X}",
                 f"\t.size\tte_retail_image, 0x{IMAGE_END - IMAGE_START:X}"]
        for i, addr in enumerate(addrs):
            nxt = addrs[i + 1] if i + 1 < len(addrs) else IMAGE_END
            for name, size in labels[addr]:
                sz = size if size else max(1, min(4, nxt - addr))
                sz = min(sz, IMAGE_END - addr)
                lines += [f"\t.globl\t{name}", f"\t.type\t{name}, %object", f"\t.set\t{name}, te_guest_block + 0x{addr:X}",
                          f"\t.size\t{name}, 0x{sz:X}"]
        lines.append("")
        Path(a.out).write_text("\n".join(lines))
        if a.json:
            Path(a.json).write_text(json.dumps({
                "image_start": IMAGE_START, "image_end": IMAGE_END, "sections": SECTIONS, "guest_size": guest_size,
                "symbols": {name: addr for addr in addrs for name, _ in labels[addr]},
                "unresolved_outside_image": unresolved_outside}, indent=1))
        print(f"gen_retail_image --arm: {sum(len(v) for v in labels.values())} symbols at {len(addrs)} addresses in the "
              f"guest block -> {a.out}" + (f"; OUTSIDE IMAGE: {unresolved_outside}" if unresolved_outside else ""))
        return 0
    lines = ["# GENERATED by tools/gen_retail_image.py -- DO NOT EDIT. The retail data image (zero-filled; bytes loaded at run time).",
             f"# range 0x{IMAGE_START:X}..0x{IMAGE_END:X}, {len(addrs)} addresses, {sum(len(v) for v in labels.values())} symbols",
             # a .bss section: zero, no bytes in the module, and wasm-ld places .bss LAST -- the image is the module's data end
             # (tools/link_wasm.py puts the C++'s data below it)
             '\t.section\t.bss.te_retail_image,"",@', "\t.globl\tte_retail_image", "\t.p2align\t4", "te_retail_image:"]
    cur = IMAGE_START
    for i, addr in enumerate(addrs):
        if addr > cur:
            lines.append(f"\t.skip\t0x{addr - cur:X}")
            cur = addr
        nxt = addrs[i + 1] if i + 1 < len(addrs) else IMAGE_END
        for name, size in labels[addr]:
            sz = size if size else max(1, min(4, nxt - addr))
            sz = min(sz, IMAGE_END - addr)
            lines.append(f"\t.globl\t{name}")
            lines.append(f"{name}:")
            lines.append(f"\t.size\t{name}, 0x{sz:X}")
    if cur < IMAGE_END:
        lines.append(f"\t.skip\t0x{IMAGE_END - cur:X}")
    lines.append(f"\t.size\tte_retail_image, 0x{IMAGE_END - IMAGE_START:X}")
    lines.append("")
    Path(a.out).write_text("\n".join(lines))

    if a.json:
        Path(a.json).write_text(json.dumps({
            "image_start": IMAGE_START, "image_end": IMAGE_END, "sections": SECTIONS,
            "symbols": {name: addr for addr in addrs for name, _ in labels[addr]},
            "unresolved_outside_image": unresolved_outside}, indent=1))
    print(f"gen_retail_image: {sum(len(v) for v in labels.values())} symbols at {len(addrs)} addresses -> {a.out}"
          + (f"; OUTSIDE IMAGE: {unresolved_outside}" if unresolved_outside else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
